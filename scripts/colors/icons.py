#!/usr/bin/env python3
"""Quiet: the folders of this desktop, drawn with the shell's own glyphs.

The shell's icons are Material Symbols Rounded, filled. So are these folders: the font's
`folder` glyph in the palette's mid-tone accent (the wallpaper's own colour with a content
scheme), and for the special folders the font's own composites (folder_code, folder_zip,
folder_shared ...) or a Material symbol cut out of the body the same way those are drawn.
Outlines come from scripts/colors/folder-glyphs.json (extracted once from the font); the
theme is regenerated by applycolor.sh on every wallpaper change. Everything that is not a
folder is inherited from Tela.
"""
import json, os, glob, subprocess, shutil

HOME = os.path.expanduser("~")
HERE = os.path.dirname(os.path.abspath(__file__))
COLORS = f"{HOME}/.local/state/quickshell/user/generated/colors.json"
BASE = "/usr/share/icons/Tela-circle-purple-dark"
NAME = "Quiet"
OUT = f"{HOME}/.local/share/icons/{NAME}"

pal = json.load(open(COLORS))
body = os.environ.get("ICON_ACCENT") or pal.get("inverse_primary", "#6b5b52")
glyphs = json.load(open(f"{HERE}/folder-glyphs.json"))

# name -> (folder glyph, symbol cut out of the body). Material's own composites carry None.
SPECIAL = {
    "folder-open": ("folder_open.fill", None),
    "user-home": ("folder.fill", "home.fill"),
    "folder-download": ("folder.fill", "download"),
    "folder-documents": ("folder.fill", "description.fill"),
    "folder-pictures": ("folder.fill", "image.fill"),
    "folder-music": ("folder.fill", "music_note"),
    "folder-videos": ("folder.fill", "movie.fill"),
    "user-desktop": ("folder.fill", "desktop_windows.fill"),
    "folder-code": ("folder_code.fill", None),
    "folder-templates": ("folder_copy.fill", None),
    "folder-publicshare": ("folder_shared.fill", None),
    "folder-tar": ("folder_zip.fill", None),
    "folder-favorites": ("folder_special.fill", None),
    "folder-locked": ("folder_limited.fill", None),
    "folder-cloud": ("folder.fill", "cloud.fill"),
    "folder-games": ("folder.fill", "sports_esports.fill"),
    "folder-script": ("folder.fill", "terminal"),
    "folder-trash": ("folder.fill", "delete.fill"),
}
ALIAS = {
    "folder-downloads": "folder-download", "folder-home": "user-home", "folder-desktop": "user-desktop",
    "folder-image": "folder-pictures", "folder-images": "folder-pictures", "folder-picture": "folder-pictures", "folder-photo": "folder-pictures",
    "folder-video": "folder-videos", "folder-sound": "folder-music", "folder-text": "folder-documents", "folder-document": "folder-documents",
    "folder-development": "folder-code", "folder-github": "folder-code", "folder-git": "folder-code", "folder-projects": "folder-code",
    "folder-public": "folder-publicshare", "folder-share": "folder-publicshare", "folder-remote": "folder-publicshare", "folder-network": "folder-publicshare",
    "folder-zip": "folder-tar", "folder-archive": "folder-tar", "folder-important": "folder-favorites", "folder-favorite": "folder-favorites", "folder-bookmark": "folder-favorites",
    "folder-private": "folder-locked", "folder-dropbox": "folder-cloud", "folder-gdrive": "folder-cloud", "folder-google-drive": "folder-cloud", "folder-onedrive": "folder-cloud", "folder-mega": "folder-cloud",
    "folder-game": "folder-games", "folder-steam": "folder-games", "folder-scripts": "folder-script", "folder-temp": "folder-trash", "user-trash": "folder-trash",
}

def svg(size, folder, sub):
    head = f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24">'
    # A symbol cut out of the body, the way the font's own folder_code/folder_zip are drawn:
    # 8.5 units in a 24 grid, centred in the body below the tab. Not below 22px: it would smear.
    if sub and size >= 22:
        g = glyphs[sub]; k = 8.5 / max(g["w"], g["h"])
        return (f'{head}<mask id="m"><rect width="24" height="24" fill="#fff"/>'
                f'<path fill="#000" fill-rule="evenodd" transform="translate(12 13.4) scale({k:.3f}) translate(-12 -12)" d="{g["d"]}"/></mask>'
                f'<path fill="{body}" mask="url(#m)" d="{glyphs[folder]["d"]}"/></svg>')
    return f'{head}<path fill="{body}" d="{glyphs[folder]["d"]}"/></svg>'

def resolve(name):
    n = ALIAS.get(name, name)
    return SPECIAL.get(n, ("folder.fill", None))

if os.path.isdir(OUT):
    shutil.rmtree(OUT)
names = sorted({os.path.basename(p)[:-4] for p in glob.glob(f"{BASE}/scalable/places/*.svg")})
names = [n for n in names if "symbolic" not in n and (n.startswith("folder") or n.startswith("user-") or n == "default-folder")]
sizes = ["16", "22", "24", "32", "48", "scalable"]
dirs = []
for d in sizes:
    path = f"{OUT}/{d}/places"; os.makedirs(path, exist_ok=True); dirs.append(f"{d}/places")
    px = 64 if d == "scalable" else int(d)
    for n in names:
        folder, sub = resolve(n)
        open(f"{path}/{n}.svg", "w").write(svg(px, folder, sub))
index = f"[Icon Theme]\nName={NAME}\nComment=Folders in the shell's glyphs and palette; everything else from Tela\nInherits=Tela-circle-purple-dark,hicolor\nDirectories={','.join(dirs)}\n\n"
for d in dirs:
    size = d.split("/")[0]
    index += (f"[{d}]\nSize=64\nMinSize=16\nMaxSize=512\nContext=Places\nType=Scalable\n\n" if size == "scalable"
              else f"[{d}]\nSize={size}\nContext=Places\nType=Fixed\n\n")
open(f"{OUT}/index.theme", "w").write(index)
subprocess.run(["gtk-update-icon-cache", "-f", "-q", OUT], check=False)
print(f"{NAME}: {len(names)} folder names x {len(dirs)} sizes, accent {body}")
